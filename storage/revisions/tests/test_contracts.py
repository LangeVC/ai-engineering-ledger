"""
Contract tests verifying compatibility between storage/revisions and schema/core contracts:
- Validates serialized revision and measurement objects against schema/core semantic checkers
- Validates JSON representation matches schema definitions
"""

import json
import os
import sys
import unittest
from pathlib import Path

from storage.revisions import (
    LineageInfo,
    MeasurementRevisionRecord,
    RevisionRecord,
    RevisionStore,
    generate_ulid,
)

# Import semantic checker from schema/core if available in main repo
AEL_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(AEL_ROOT))

try:
    from schema.core import semantic
except ImportError:
    semantic = None


class TestRevisionContracts(unittest.TestCase):

    def setUp(self):
        self.store = RevisionStore(":memory:")
        self.catalog_path = AEL_ROOT / "schema/core/units.catalog.json"
        if self.catalog_path.exists():
            with open(self.catalog_path, "r", encoding="utf-8") as f:
                self.units_catalog = json.load(f)
        else:
            self.units_catalog = None

    def test_record_matches_schema_semantic_checker(self):
        """Ensure records generated by storage/revisions conform to schema/core/semantic.py rules."""
        if semantic is None or self.units_catalog is None:
            self.skipTest("schema/core/semantic.py or units.catalog.json not available")

        ev_id = "ev_01J9Z3K5Q8W2X4Y6A7B8C9D0AA"
        self.store.register_evidence(
            evidence_id=ev_id,
            source="byteplus",
            source_account_id="bp01",
            raw_bytes=b"sample payload",
        )

        mid = generate_ulid()
        eid = generate_ulid()
        rev1 = RevisionRecord(
            revision_id=generate_ulid(),
            revision_no=1,
            supersedes=None,
            reason_code="initial",
            reason="initial reading",
            recorded_at="2026-10-26T01:00:00Z",
            effective=True,
            lineage=LineageInfo(
                mapping_version="0.1.0",
                transformation_version="0.1.0",
                input_measurement_ids=[],
            ),
        )
        meas = MeasurementRevisionRecord(
            schema_version="0.1",
            measurement_id=mid,
            event_id=eid,
            metric="input_tokens",
            value=1500,
            unit="token",
            aggregation="interval_total",
            source="byteplus",
            source_account_id="bp01",
            provenance={
                "class": "P0",
                "method": "api",
                "confidence": 1.0,
                "confidence_reason": "api extract",
                "validation_status": "semantically_checked",
            },
            evidence_ids=[ev_id],
            collector_version="1.0.0",
            mapping_version="0.1.0",
            revision=rev1,
        )

        self.store.record_initial_measurement(meas)

        # Check semantic.check_measurement
        meas_dict = meas.to_dict()
        errors = semantic.check_measurement(meas_dict, self.units_catalog)
        self.assertEqual(errors, [], f"Semantic measurement validation failed: {errors}")

        # Apply correction
        corr = self.store.correct_measurement(
            measurement_id=mid,
            new_value=1750,
            reason_code="reading_error",
            reason="corrected token count",
            actor="engineer_bob",
        )
        corr_dict = corr.to_dict()
        errors = semantic.check_measurement(corr_dict, self.units_catalog)
        self.assertEqual(errors, [], f"Semantic measurement validation on correction failed: {errors}")

        # Check semantic.check_revision_chain on full history
        history = self.store.get_revision_history(mid)
        raw_rev_list = [h.revision.to_dict() for h in history]
        chain_errors = semantic.check_revision_chain(raw_rev_list)
        self.assertEqual(chain_errors, [], f"Semantic revision chain validation failed: {chain_errors}")


if __name__ == "__main__":
    unittest.main()
